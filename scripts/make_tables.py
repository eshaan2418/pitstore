"""Tables (eval/results/tables.md) and plot (eval/plots/leakage.png) from raw JSON."""

import json
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

R = json.loads(Path("eval/results/leakage.json").read_text())
B = json.loads(Path("eval/results/bench_asof.json").read_text())
LABEL = {"correct": "point-in-time correct", "snapshot": "snapshot join (latest features)",
         "window_leak": "off-by-one-window timestamp"}


def ci(xs):
    mu = float(np.mean(xs))
    return mu, 4.303 * float(np.std(xs, ddof=1)) / math.sqrt(len(xs))


out = ["# Results (generated by scripts/make_tables.py)\n",
       f"Rows: {R['n_rows']:,} (customer x month), positive rate {R['positive_rate']:.3f}; "
       f"split rows {R['rows_per_split']}.\n",
       "| feature pipeline | leak-check violations (of 200) | offline test AUC (what you "
       "report) | deployed test AUC (what you get) | gap |", "|---|---|---|---|---|"]
for k, v in R["pipelines"].items():
    off = ci([s["offline_test_auc"] for s in v["seeds"]])
    dep = ci([s["deployed_test_auc"] for s in v["seeds"]])
    boot = v["seeds"][0]
    out.append(f"| {LABEL[k]} | {v['leak_check_violations']} | {off[0]:.3f} ± {off[1]:.3f} "
               f"(bootstrap {boot['offline_ci'][0]:.3f}-{boot['offline_ci'][1]:.3f}) | "
               f"{dep[0]:.3f} ± {dep[1]:.3f} (bootstrap {boot['deployed_ci'][0]:.3f}-"
               f"{boot['deployed_ci'][1]:.3f}) | {off[0] - dep[0]:+.3f} |")
rs = R["snapshot_random_split_auc"]
out.append(f"\nSnapshot features with a random (not temporal) 80/20 split: AUC "
           f"{np.mean(rs):.3f} (3 seeds: {', '.join(f'{x:.3f}' for x in rs)}).\n")
out += ["## As-of window aggregation speed (synthetic; sum over a 1-hour window, 60 s delay)\n",
        "| events | queries | pitstore build s | pitstore query s | pandas (merge_asof) s | "
        "Python loop s |", "|---|---|---|---|---|---|"]
for r in B["rows"]:
    loop = f"{r['python_loop_s']:.3f}" if "python_loop_s" in r else "-"
    out.append(f"| {r['events']:,} | {r['queries']:,} | {r['pitstore_build_s']:.3f} | "
               f"{r['pitstore_query_s']:.3f} | {r['pandas_s']:.3f} | {loop} |")
Path("eval/results/tables.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
fig, ax = plt.subplots(figsize=(6, 3.2))
names = list(R["pipelines"])
x = np.arange(len(names))
off = [np.mean([s["offline_test_auc"] for s in R["pipelines"][k]["seeds"]]) for k in names]
dep = [np.mean([s["deployed_test_auc"] for s in R["pipelines"][k]["seeds"]]) for k in names]
ax.bar(x - 0.2, off, 0.4, label="offline estimate", color="#DD8452")
ax.bar(x + 0.2, dep, 0.4, label="deployed (correct features)", color="#4C72B0")
ax.set_xticks(x, [LABEL[k] for k in names], fontsize=7)
ax.set_ylim(0.5, 1.0)
ax.set_ylabel("test AUC")
ax.spines[["top", "right"]].set_visible(False)
ax.legend(frameon=False, fontsize=8)
fig.tight_layout()
Path("eval/plots").mkdir(parents=True, exist_ok=True)
fig.savefig("eval/plots/leakage.png", dpi=150)
